#!/usr/bin/env bash
# The local Yantra web: every apps/<id>/app.json becomes an entry in apps/desktop/catalog.nim,
# the list the desktop's search offers. Run after adding or renaming an app.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/apps/desktop/catalog.nim"
field() { sed -n "s/.*\"$2\": *\"\([^\"]*\)\".*/\1/p" "$1" | head -1; }
{
  echo "## Generated by tools/apps-index.sh from apps/*/app.json — do not edit."
  echo "type CatalogApp* = object"
  echo "  id*, name*, icon*: string"
  echo "  tint*: int                 ## the icon tile's colour"
  echo "const catalog*: seq[CatalogApp] = @["
  for j in "$ROOT"/apps/*/app.json; do
    tint="$(field "$j" tint)"; tint="0x${tint#\#}"; [ "$tint" = "0x" ] && tint="0x8E8E93"
    echo "  CatalogApp(id: \"$(field "$j" id)\", name: \"$(field "$j" name)\", icon: \"$(field "$j" icon)\", tint: $tint),"
  done
  echo "]"
} > "$OUT"
echo "apps-index: $(grep -c 'CatalogApp(' "$OUT") apps -> $OUT"
